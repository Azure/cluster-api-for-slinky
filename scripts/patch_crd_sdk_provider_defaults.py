"""Patch crd2pulumi SDKs to defer provider selection to Kubernetes tokens."""

from __future__ import annotations

import argparse
import ast
from dataclasses import dataclass
from pathlib import Path
import sys


@dataclass(frozen=True)
class Target:
    relative_path: Path
    package_name: str
    example_token: str
    plugin_name: str


TARGETS = (
    Target(
        relative_path=Path(
            "pulumi/sdks/capi-core/"
            "pulumi_ca4s_capi_core_crds/_utilities.py"
        ),
        package_name="ca4s-capi-core-crds",
        example_token="kubernetes:cluster.x-k8s.io/v1beta2:Cluster",
        plugin_name="pulumi-resource-ca4s-capi-core-crds",
    ),
    Target(
        relative_path=Path("pulumi/sdks/flux/ca4s_flux_crds/_utilities.py"),
        package_name="flux-crds",
        example_token="kubernetes:source.toolkit.fluxcd.io/v1:GitRepository",
        plugin_name="pulumi-resource-flux-crds",
    ),
)


def _replacement(target: Target, function_name: str) -> str:
    if function_name == "get_resource_opts_defaults":
        return (
            "def get_resource_opts_defaults() -> pulumi.ResourceOptions:\n"
            f"    # crd2pulumi generated this shim as ``{target.package_name}``, but its\n"
            "    # resource tokens are Kubernetes tokens, for example:\n"
            f"    # ``{target.example_token}``.\n"
            "    # Attaching shim defaults makes Pulumi try to install the nonexistent\n"
            f"    # ``{target.plugin_name}`` provider plugin.\n"
            "    return pulumi.ResourceOptions()\n"
        )
    if function_name == "get_invoke_opts_defaults":
        return (
            "def get_invoke_opts_defaults() -> pulumi.InvokeOptions:\n"
            "    return pulumi.InvokeOptions()\n"
        )
    raise ValueError(f"unsupported function: {function_name}")


def patch_source(source: str, target: Target) -> str:
    if "generated by crd2pulumi" not in "\n".join(source.splitlines()[:5]):
        raise ValueError("missing crd2pulumi generated-file marker")

    tree = ast.parse(source)
    function_names = {"get_resource_opts_defaults", "get_invoke_opts_defaults"}
    functions = {
        node.name: node
        for node in tree.body
        if isinstance(node, ast.FunctionDef) and node.name in function_names
    }
    missing = function_names - functions.keys()
    if missing:
        raise ValueError(f"missing generated functions: {', '.join(sorted(missing))}")

    lines = source.splitlines(keepends=True)
    for function_name, node in sorted(
        functions.items(), key=lambda item: item[1].lineno, reverse=True
    ):
        if node.end_lineno is None:
            raise ValueError(f"cannot determine source span for {function_name}")
        lines[node.lineno - 1 : node.end_lineno] = _replacement(
            target, function_name
        ).splitlines(keepends=True)
    return "".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--root",
        type=Path,
        default=Path(__file__).resolve().parents[1],
        help="repository root containing pulumi/sdks (default: inferred)",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="report files that need patching without modifying them",
    )
    args = parser.parse_args()

    failed = False
    for target in TARGETS:
        path = args.root / target.relative_path
        try:
            source = path.read_text(encoding="utf-8")
            patched = patch_source(source, target)
        except (OSError, SyntaxError, ValueError) as error:
            print(f"error: {target.relative_path}: {error}", file=sys.stderr)
            failed = True
            continue

        if patched == source:
            print(f"unchanged: {target.relative_path}")
        elif args.check:
            print(f"needs patch: {target.relative_path}", file=sys.stderr)
            failed = True
        else:
            path.write_text(patched, encoding="utf-8")
            print(f"patched: {target.relative_path}")

    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())